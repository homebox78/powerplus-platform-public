    private static function norm(string $s): string
    {
        return (string) preg_replace('/[\s,*]/u', '', $s);   // 마크다운 굵게(**191**)도 지운다
    }

    /**
     * 수치 표기 맞추기 — '53퍼센트'·'53 %' → 53%, '32억 4천만원' → 32.4억, '5백억' → 500억, '500(억원)'·'500억 원' → 500억.
     * 같은 수를 다른 표기로 썼다고 치명으로 막던 것(2026-10-12 MCP 시험 a02·x1)
     */
    private static function canon(string $t): string
    {
        return (string) preg_replace(
            ['/(\d)\s*퍼센트/u', '/(\d[\d,]*)\s*억\s*(\d)\s*천\s*만?\s*(?:원)?/u', '/(\d)\s*백\s*억/u', '/(\d[\d,]*(?:\.\d+)?)\s*\(\s*(억|만|천)\s*원\s*\)/u', '/(\d)\s+(%|억|만|천|조)(?![가-힣])/u', '/(\d)\s+(억|만|천|조)/u', '/(\d)(억|만|천|조)\s*원/u'],
            ['$1%', '$1.$2억', '${1}00억', '$1$2', '$1$2', '$1$2', '$1$2'],
            $t
        );
    }

    /** 대조용 평문 — 표기를 맞추고 공백·쉼표·굵게를 지운다 */
    private static function flat(string $t): string
    {
        return self::norm(self::canon($t));
    }

    /** 평문 안에 그 수치가 따로 있는가 — '9일' 이 '19일' 안에, '2개' 가 '2개월' 안에 있다고 보지 않게 */
    private static function has(string $flat, string $key): bool
    {
        if ($key === '') return false;
        $tail = preg_match('/\d$/u', $key) ? '(?![\d.]\d|\d)' : (str_ends_with($key, '개') ? '(?!월|소)' : '');
        return (bool) preg_match('/(?<![\d.])' . preg_quote($key, '/') . $tail . '/u', $flat);
    }

    /** 칸 값을 글로 — 배열(줄 목록)로 보낸 content·lines 도 받는다('Array to string' 오류, 2026-10-12 a18) */
    private static function str(mixed $v): string
    {
        if (is_array($v)) return implode("\n", array_map(static fn($x) => self::str($x), $v));
        if (is_scalar($v)) return (string) $v;
        return '';
    }

