    /** 수치 목록 — design.py fact_check 와 같은 거름(한 자리 수는 %·기간·개수 단위일 때만, 앞자리 0 연번 제외) */
    private static function nums(string $text): array
    {
        $out = [];
        $text = self::canon($text);
        if (!preg_match_all(self::NUM, $text, $m, PREG_OFFSET_CAPTURE)) return $out;
        foreach ($m[0] as [$raw, $off]) {
            if (preg_match(self::VERSION_BEFORE, substr($text, max(0, $off - 12), min($off, 12)))) continue;
            $raw = trim($raw);
            if (!preg_match('/^\d[\d,]*(?:\.\d+)?/u', $raw, $c)) continue;
            $core = self::norm($c[0]);
            $unit = trim(mb_substr($raw, mb_strlen($c[0])));
            // 한 자리 수도 기간·개수 단위면 센다 — '7일→9일'·'3일→1일' 날조를 놓치던 것(2026-10-12 MCP 시험). 장·월·점·위는 번호와 섞여 뺀다
            if (mb_strlen($core) < 2 && !preg_match('/^(?:%|일|시간|개월|곳|건|명|배|억|만|조|천|원|개소|종|년|회|분)/u', $unit)) continue;
            if (preg_match('/^0\d/', $core)) continue;
            $out[] = ['raw' => $raw, 'core' => $core, 'unit' => $unit, 'key' => self::norm($raw)];
        }
        return $out;
    }

