    /**
     * 기획 판정. in: {plan:{title,core,slides:[…]} 또는 slides 를 바로, source?: 원자료 글, slide_count?: 기대 장 수}
     */
    public static function checkPlan(array $in): array
    {
        $plan = is_array($in['plan'] ?? null) ? $in['plan'] : $in;
        $slides = is_array($plan['slides'] ?? null) ? array_values(array_map([self::class, 'flatSlide'], array_filter($plan['slides'], 'is_array'))) : [];
        $source = self::str($in['source'] ?? '');
        $issues = [];
        $add = static function (?int $n, string $sev, string $issue, string $fix) use (&$issues): void {
            $issues[] = ['where' => $n === null ? '전체' : $n . '쪽', 'severity' => $sev, 'issue' => $issue, 'fix' => $fix];
        };
        if (!$slides) {
            $add(null, 'fatal', 'slides 배열이 비었습니다 — 판정할 장이 없습니다', '{"title","core","slides":[{"n":1,"title","message","mood","content"},…]} 형식으로 장을 하나 이상 보내세요');
            return self::score($issues, ['slides' => 0]);
        }
        if (trim((string) ($plan['core'] ?? '')) === '') $add(null, 'warn', 'core(제안 전체 한 문장)가 없습니다', '모든 장의 message 가 이어질 한 문장을 core 에 적으세요');
        $want = (int) ($in['slide_count'] ?? 0);
        if ($want > 0 && count($slides) < $want * 0.6) {
            // 요청한 장 수의 60%도 못 채우면 통과시키지 않는다(2026-10-12 MCP 시험)
            $add(null, 'fatal', '장 수가 ' . count($slides) . '장으로 요청 ' . $want . '장에 크게 모자랍니다', '빠진 장을 채우세요 — 배점 큰 항목부터 장을 나눕니다');
        } elseif ($want > 0 && abs(count($slides) - $want) > max(1, (int) round($want * 0.2))) {
            $add(null, 'warn', '장 수가 ' . count($slides) . '장입니다(요청 ' . $want . '장)', '분량이 넘치는 장은 (1/2)(2/2) 로 나누고, 얇은 장은 합치세요');
        }
        // 발표 시간 대비 장 수(DCK-104) — 한 장 60~80초. 분은 요청(minutes) 또는 원자료의 '발표 규정'에서, 분량 상한이 있으면 그 값이 먼저
        $minutes = (float) ($in['minutes'] ?? 0) ?: (float) (self::presentMinutes($source) ?? 0);
        $cap = self::slideCap($source);
        if ($minutes > 0 || $cap) {
            [$lo, $hi] = $minutes > 0 ? self::paceRange($minutes) : [1, $cap];
            if ($cap) { $hi = min($hi, $cap); $lo = min($lo, $hi); }
            $cnt = count($slides);
            $why = ($minutes > 0 ? '발표 ' . rtrim(rtrim(number_format($minutes, 1), '0'), '.') . '분' : '') . ($cap ? ($minutes > 0 ? ', ' : '') . '분량 상한 ' . $cap . '장' : '');
            if ($cnt > $hi) $add(null, 'warn', '장 수가 ' . $cnt . '장으로 ' . $why . ' 기준(' . $lo . '~' . $hi . '장)보다 많습니다', '한 장 60~80초 — 덜 중요한 장을 합치거나 빼세요' . ($cap ? '(분량 상한은 넘기면 안 됩니다)' : ''));
            elseif ($cnt < $lo) $add(null, count(self::evalItems($source)) >= 3 ? 'warn' : 'info', '장 수가 ' . $cnt . '장으로 ' . $why . ' 기준(' . $lo . '~' . $hi . '장)보다 적습니다', '배점 상위 항목을 2장으로 나눠 근거를 더하세요');
        }
        // 평가 항목명 원문이 장 제목·절 이름에 있는가(DCK-101) — 위원이 채점표와 장표를 1:1 로 맞춰 본다
        $items = self::evalItems($source);
        $stat0 = [];
        if (count($items) >= 3) {
            // 배점 순위(2026-10-12 MCP 시험) — 상위 항목이 덱 뒤쪽에 몰리거나 한 장뿐이면 경고
            $looseP = static fn(string $t): string => (string) preg_replace('/(?:및|·|ㆍ|,|&)/u', '', self::norm($t));
            $cntAll = count($slides);
            $rank = [];
            foreach (array_slice($items, 0, 3, true) as $name => $pt) {
                $k = $looseP($name);
                $pos = [];
                foreach ($slides as $i => $s) if (str_contains($looseP(($s['title'] ?? '') . '|' . ($s['section'] ?? '') . '|' . ($s['chapter'] ?? '') . '|' . ($s['message'] ?? '')), $k)) $pos[] = $i;
                $rank[] = ['item' => $name, 'points' => $pt, 'slides' => count($pos), 'first' => $pos ? $pos[0] + 1 : null];
                if (count($pos) === 1 && $cntAll >= 6) $add(null, 'warn', '배점 상위 항목 "' . $name . '"(' . $pt . '점)을 한 장만 다룹니다', '배점이 큰 항목은 2장 이상 — 근거·사례 장을 하나 더하세요');
            }
            $firsts = array_values(array_filter(array_column($rank, 'first')));
            if (count($firsts) >= 2 && $cntAll >= 6 && array_sum($firsts) / count($firsts) > $cntAll * 0.6) {
                $add(null, 'warn', '배점 상위 항목이 덱 뒤쪽(평균 ' . round(array_sum($firsts) / count($firsts)) . '쪽 / ' . $cntAll . '장)에 몰려 있습니다', '배점 큰 항목을 앞쪽(전체의 앞 절반)으로 당기세요 — 위원은 앞에서 점수를 정합니다');
            }
            $stat0['priority'] = $rank;
        }
        if (count($items) >= 3) {
            $loose = static fn(string $t): string => (string) preg_replace('/(?:및|·|ㆍ|,|&)/u', '', self::norm($t));
            $heads = array_map(static fn($s) => $loose(($s['title'] ?? '') . '|' . ($s['section'] ?? '') . '|' . ($s['chapter'] ?? '')), $slides);
            $hit = [];
            foreach (array_keys($items) as $name) {
                $k = $loose($name);
                foreach ($heads as $h) if (str_contains($h, $k)) { $hit[] = $name; break; }
            }
            $missTop = array_values(array_diff(array_slice(array_keys($items), 0, 3), $hit));
            if (!$hit) $add(null, 'warn', '평가 항목명(' . count($items) . '개)이 장 제목·절 이름에 하나도 없습니다', '배점 큰 항목부터 평가 항목명 원문(예: "' . array_key_first($items) . '")을 그 장의 title 이나 section 에 그대로 쓰세요');
            elseif ($missTop) $add(null, 'info', '배점 상위 항목이 장 제목·절 이름에 없습니다: ' . implode(', ', $missTop), '그 항목에 답하는 장의 title·section 에 항목명을 그대로 쓰세요');
        }
        // 첫 장 = 발주처 수치 되돌려 주기(DCK-102) — 원자료의 단위 있는 수치가 2개 이상 그대로
        if (trim($source) !== '') {
            $srcKeys = [];
            foreach (self::nums($source) as $x) if ($x['unit'] !== '') $srcKeys[$x['key']] = true;
            $s0 = $slides[0];
            $have = [];
            foreach (self::nums(($s0['title'] ?? '') . "\n" . ($s0['message'] ?? '') . "\n" . ($s0['content'] ?? '')) as $x) if (isset($srcKeys[$x['key']])) $have[$x['key']] = true;
            if ($srcKeys && count($have) < 2) $add((int) ($s0['n'] ?? 1), 'warn', '첫 장에 발주처 자료의 수치가 ' . count($have) . '개뿐입니다', '발주처가 쓴 핵심 수치 2개 이상을 원문 그대로 되돌려 주세요(예산·대상 규모·처리 건수 등)');
        }
        // 얇은 장 기준 — 원자료가 짧으면 장당 원자료 분량에 맞춰 낮춘다(없는 내용을 지어 채우지 않게, 2026-10-12)
        $srcPer = trim($source) !== '' ? mb_strlen((string) preg_replace('/\s+/u', ' ', $source)) / max(1, count($slides)) : 0;
        $thinFloor = static fn(int $lo): int => $srcPer > 0 ? max(60, min((int) ($lo * 0.8), (int) ($srcPer * 1.2))) : (int) ($lo * 0.8);
        $seenN = [];
        $prevDevice = '';
        foreach ($slides as $i => $s) {
            $n = (int) ($s['n'] ?? 0);
            if ($n <= 0) { $add(null, 'fatal', ($i + 1) . '번째 장에 n(쪽 번호)이 없습니다', 'n 을 1부터 차례로 붙이세요'); $n = $i + 1; }
            if (isset($seenN[$n])) $add($n, 'fatal', '쪽 번호 ' . $n . '이 겹칩니다', '쪽 번호를 하나씩만 쓰세요');
            $seenN[$n] = true;
            foreach (['title', 'message', 'mood', 'content'] as $k) {
                if (trim((string) ($s[$k] ?? '')) === '') $add($n, 'fatal', $k . ' 가 비었습니다', $k . ' 를 채우세요');
            }
            $title = (string) ($s['title'] ?? '');
            $tl = mb_strlen($title);
            if ($tl > 36) $add($n, 'warn', '헤드라인이 ' . $tl . '자로 깁니다(한 줄 31자 안팎)', '주장만 남겨 줄이세요');
            foreach (['title', 'message', 'scene', 'layout'] as $k) {
                if (preg_match('/\*\*|^#|\s#{1,6}\s/u', (string) ($s[$k] ?? ''))) $add($n, 'warn', $k . ' 에 마크다운 기호가 있습니다', '** · # 를 빼고 글만 쓰세요');
            }
            $kw = trim((string) ($s['keyword'] ?? ''));
            if ($kw !== '') {
                foreach (array_filter(array_map('trim', explode(',', $kw))) as $w) {
                    if (!str_contains($title, $w)) $add($n, 'warn', 'keyword "' . $w . '" 가 헤드라인에 글자 그대로 없습니다', 'title 안에 있는 말로 고르세요');
                }
            }
            $mood = trim((string) ($s['mood'] ?? ''));
            if ($mood !== '' && !in_array($mood, self::MOODS, true)) {
                $near = Triage::mood($mood, $title, self::MOODS);
                $add($n, 'warn', 'mood "' . $mood . '" 는 정해진 값이 아닙니다', ($near ? '"' . $near . '" 가 가장 가깝습니다. ' : '') . implode(' / ', self::MOODS) . ' 중 하나로');
                if ($near) $mood = $near;
            }
            $content = (string) ($s['content'] ?? '');
            $len = mb_strlen($content);
            [$lo, $hi] = self::lengthFor($mood);
            if ($len > 600) $add($n, 'warn', 'content 가 ' . $len . '자로 600자를 넘습니다', '(1/2)(2/2) 두 장으로 나누세요');
            elseif ($len > 0 && $len < $thinFloor($lo)) $add($n, 'warn', 'content 가 ' . $len . '자로 얇습니다(' . $mood . ' 기준 ' . $lo . '~' . $hi . '자' . ($thinFloor($lo) < (int) ($lo * 0.8) ? ', 원자료가 짧아 ' . $thinFloor($lo) . '자까지 허용' : '') . ')', '원자료에서 항목·수치·이름·단계를 더 찾아 채우세요');
            $gaps = substr_count($content, '보강 필요');
            if ($gaps > 2) $add($n, 'warn', '"※ 보강 필요"가 ' . $gaps . '개입니다', '아는 항목만으로 구성을 다시 짜세요(빈 칸투성이 표 금지)');
            if (preg_match('/(?:^|[\s(])0\d[.)·]/um', $content)) $add($n, 'info', '앞자리 0 연번(01·02)이 있습니다', '1·2·3 으로 쓰세요');
            $device = trim((string) ($s['device'] ?? ''));
            if ($device !== '' && $device === $prevDevice) $add($n, 'info', '앞 장과 같은 장치(' . $device . ')입니다', '연속 장이면 (1/2)(2/2) 로 묶고, 아니면 장치를 바꾸세요');
            $prevDevice = $device;
            // 글 위생 — 메타 문구·워터마크·과장·추상 약속
            $txt = $title . "\n" . ($s['message'] ?? '') . "\n" . $content;
            if (preg_match_all(self::META, $txt, $m)) foreach (array_unique($m[0]) as $x) $add($n, 'warn', '만드는 사람을 위한 설명이 장표 글에 있습니다: "' . $x . '"', 'layout·scene 으로 옮기세요');
            if (preg_match_all(self::WATERMARK, $txt, $m)) foreach (array_unique($m[0]) as $x) $add($n, 'warn', '도구 이름·워터마크로 보이는 글: "' . $x . '"', '지우세요');
            if (preg_match(self::ECHO_TAIL, $txt, $m)) $add($n, 'warn', '평가 항목을 되받는 꼬리로 끝납니다: "' . trim($m[0]) . '"', '그 평가 항목에 무엇을 주는지(산출물·수치·기한)로 끝맺으세요');
            foreach (self::HYPE as $h) {
                if (str_contains($txt, $h) && !str_contains($source, $h)) $add($n, 'warn', '"' . $h . '" 같은 강한 표현의 근거가 원자료에 없습니다', '범위·출처·시점을 붙인 구체적인 말로 바꾸세요');
            }
            foreach (preg_split('/[\n.]/u', $txt) as $ln) {
                if (preg_match(self::VAGUE, $ln) && !preg_match('/\d/', $ln)) {
                    $add($n, 'info', '추상적인 약속: "' . mb_substr(trim($ln), 0, 40) . '"', '산출물·기한·수치로 바꾸세요(예: 착수 2주 내 ○○ 보고서)');
                    break;
                }
            }
        }
        // 원자료 수치 대조 — 근거 없는 수치(변조 의심 포함)와 빠진 수치
        $stat = ['slides' => count($slides)] + $stat0;
        if (trim($source) !== '') {
            $planTxt = implode("\n", array_map(static fn($s) => ($s['title'] ?? '') . "\n" . ($s['message'] ?? '') . "\n" . ($s['content'] ?? ''), $slides));
            $srcNums = self::nums($source);
            // 평가 규정 줄(배점·발표 시간·장 수 제한·질의응답)의 수치 — 누락 대조에서 뺀다(2026-10-12 /powermcp 예시 시험: "15분·20장·90점" 을 빠뜨렸다고 함)
            $ruleNum = [];
            foreach (preg_split('/\R/u', $source) as $ln) {
                if (!preg_match('/배점|평가\s*(기준|항목)|발표\s*(시간|평가)|질의\s*응답|장표\s*:|이내|기술\s*\d+\s*점|가격\s*\d+\s*점|^\s*\|.*\|\s*\d+\s*\|?\s*$/u', $ln)) continue;
                foreach (self::nums($ln) as $rn) $ruleNum[$rn['key']] = true;
            }
            $planNums = self::nums($planTxt);
            $srcFlat = self::norm($source);
            $byUnit = [];
            foreach ($srcNums as $sn) $byUnit[$sn['unit']][] = $sn['raw'];
            // 원자료에 단위 없이 적힌 수(표 칸 "**191**")는 기획에서 단위를 붙여도 같은 수로 본다
            $bare = [];
            foreach ($srcNums as $sn) if ($sn['unit'] === '') $bare[$sn['core']] = true;
            $unknown = 0;
            foreach ($slides as $s) {
                $n = (int) ($s['n'] ?? 0);
                $seen = [];
                foreach (self::nums(($s['title'] ?? '') . "\n" . ($s['message'] ?? '') . "\n" . ($s['content'] ?? '')) as $pn) {
                    if (isset($seen[$pn['key']])) continue;
                    $seen[$pn['key']] = true;
                    if (str_contains($srcFlat, $pn['key']) || ($pn['unit'] === '' && str_contains($srcFlat, $pn['core'])) || isset($bare[$pn['core']])) continue;
                    $unknown++;
                    $near = $pn['unit'] !== '' ? array_slice(array_unique($byUnit[$pn['unit']] ?? []), 0, 3) : [];
                    $add($n, 'fatal', '수치 "' . $pn['raw'] . '" 가 원자료에 없습니다' . ($near ? ' (원자료의 같은 단위 수치: ' . implode(', ', $near) . ')' : ''),
                        $near ? '원자료 값으로 바로잡거나, 다른 항목이면 근거를 밝히세요' : '근거를 확인하거나 "※ 보강 필요: 무엇" 으로 바꾸세요');
                }
            }
            $planFlat = self::norm($planTxt);
            $missing = [];
            foreach ($srcNums as $sn) {
                if ($sn['unit'] === '') continue;   // 단위 없는 숫자(연도 외 번호 등)는 누락으로 세지 않는다
                if (isset($ruleNum[$sn['key']])) continue;   // 배점·발표 시간·장 수 제한 같은 평가 규정 수치는 장표 내용이 아니다
                if (!str_contains($planFlat, $sn['key'])) $missing[$sn['key']] = $sn['raw'];
            }
            if ($missing) {
                $list = array_values($missing);
                $add(null, 'warn', '원자료의 수치 ' . count($list) . '개가 기획에 없습니다: ' . implode(', ', array_slice($list, 0, 8)) . (count($list) > 8 ? ' 외' : ''),
                    '빠뜨린 항목이면 해당 장 content 에 넣으세요(의도적으로 뺀 것이면 그대로 두어도 됩니다)');
            }
            $stat += ['source_numbers' => count($srcNums), 'plan_numbers' => count($planNums), 'unsupported' => $unknown, 'missing' => count($missing)];
            // 덱 안 일관성 — 같은 낱말 + 단위에 다른 값
            $seenVal = [];
            foreach ($slides as $s) {
                $t = ($s['title'] ?? '') . "\n" . ($s['message'] ?? '') . "\n" . ($s['content'] ?? '');
                if (preg_match_all('/([가-힣A-Za-z]{2,12})\s*(?:은|는|이|가|:)?\s*(\d[\d,]*(?:\.\d+)?)\s*(%|억|조|만|원|명|건|개|곳|종|개월|일|시간|배|점|회)/u', $t, $mm, PREG_SET_ORDER)) {
                    foreach ($mm as $x) $seenVal[$x[1] . '|' . $x[3]][str_replace(',', '', $x[2])][(int) ($s['n'] ?? 0)] = true;
                }
            }
            foreach ($seenVal as $k => $vals) {
                if (count($vals) < 2) continue;
                // 값들이 늘 같은 장에 함께 나오면 한 낱말에 붙은 서로 다른 항목이다("평균 7일" 처리 기간·"평균 2.4일" 이관 지연, 2026-10-12 시험 오탐)
                $sets = array_map(static fn(array $ns): string => implode(',', array_keys($ns)), $vals);
                if (count(array_unique($sets)) === 1) continue;
                [$w, $u] = explode('|', $k);
                $where = implode(' / ', array_map(static fn($v, $ns) => $v . $u . '(' . implode(',', array_keys($ns)) . '쪽)', array_keys($vals), $vals));
                $add(null, 'warn', '"' . $w . '" 수치가 장마다 다릅니다: ' . $where, '하나로 맞추거나 서로 다른 항목임을 밝히세요');
            }
        } else {
            $stat['source'] = '원자료를 보내지 않아 수치 대조를 건너뛰었습니다';
        }
        return self::score($issues, $stat);
    }

    /** 발표 시간(분) — 원자료의 '발표 20분'·'발표 시간: 15분' 꼴. 질의 시간은 빼고 본다. 없으면 null */
    public static function presentMinutes(string $src): ?float
    {
        if (preg_match('/발표\s*(?:시간)?\s*[:|：]?\s*\**\s*(?:은|는)?\s*(\d{1,3})\s*분/u', str_replace('*', '', $src), $m)) {
            $v = (float) $m[1];
            return $v >= 3 && $v <= 120 ? $v : null;
        }
        return null;
    }

    /** 발표 자료 분량 상한(장) — '발표자료 20장 이내' 꼴. 제출용 본문 상한(수백 쪽)은 발표 장 수가 아니므로 60장 넘으면 버린다 */
    public static function slideCap(string $src): ?int
    {
        if (preg_match('/(?:분량|발표\s*자료|매수|장\s*수|슬라이드)[^\n]{0,30}?(\d{1,3})\s*(?:장|쪽|매|페이지|p)\s*(?:이내|이하)/u', str_replace('*', '', $src), $m)) {
            $v = (int) $m[1];
            return $v >= 3 && $v <= 60 ? $v : null;
        }
        return null;
    }

    /** 발표 분 → 적정 장 수 범위(한 장 60~80초): 10분 8~10 · 15분 12~15 · 20분 15~18 · 25~30분 18~24 */
    public static function paceRange(float $min): array
    {
        if ($min <= 10) return [max(2, (int) round($min * 0.8)), max(3, (int) round($min))];
        if ($min <= 15) return [(int) round(12 * $min / 15), (int) round($min)];
        if ($min <= 20) return [15, 18];
        if ($min <= 30) return [18, 24];
        return [(int) round($min * 0.6), (int) round($min * 0.8)];
    }

    /**
     * 평가 항목명 → 배점(큰 순). 원자료의 배점 표(머리에 '배점' 칸이 있는 표)와 "항목명(10점)" 꼴에서 뽑는다.
     * 기술·가격평가 합계, 정량·신용 같은 묶음 이름은 뺀다.
     */
    public static function evalItems(string $src): array
    {
        $skip = '/(기술\s*(?:능력)?\s*평가|가격\s*평가|입찰\s*가격|정량|정성|합계|소계|총점|신용|경영\s*상태|평점|등급|계량|배점|평가\s*(?:부문|항목|방식|분야)|^구분$|^항목$|^부문$|가점|감점)/u';
        $clean = static fn(string $c): string => trim((string) preg_replace(['/\*+/u', '/^[\s•·\-–]+/u', '/\s*\([^)]*\)\s*/u', '/\s+/u'], ['', '', ' ', ' '], $c));
        // 문장 조각("자료로 보면 …", "과 전략…")·로마자 번호·+ 로 묶은 이름은 항목명이 아니다
        $valid = static function (string $n) use ($skip): ?string {
            $n = trim((string) preg_replace('/^(?:[IVX]{1,4}|\d{1,2}[.)]?|[가나다라마바사아자차카타파하][.)])\s+/u', '', $n));
            if ($n === '' || !preg_match('/[가-힣]{2}/u', $n) || preg_match($skip, $n)) return null;
            if (preg_match('/^(?:과|와|및|의|을|를|은|는)\s|\+|기준으로|자료로|보면|비추어|에\s*따라|대한|이전/u', $n)) return null;
            if (mb_strlen($n) > 24 || count(preg_split('/\s+/u', $n)) > 5) return null;
            return $n;
        };
        $out = [];
        $inTable = false;
        foreach (preg_split('/\R/u', $src) as $ln) {
            $t = trim($ln);
            if ($t === '' || $t[0] !== '|') { $inTable = false; }
            else {
                $cells = array_map('trim', explode('|', trim($t, '|')));
                if (!$inTable) { $inTable = (bool) preg_grep('/배점/u', $cells); continue; }
                if (preg_match('/^[\s:\-|]+$/u', $t)) continue;
                for ($i = count($cells) - 1; $i > 0; $i--) {
                    $c = str_replace('*', '', $cells[$i]);
                    if (!preg_match('/^\(?\s*(\d{1,2}(?:\.\d)?)\s*점?\s*\)?$/u', $c, $pm)) continue;
                    for ($j = $i - 1; $j >= 0; $j--) {
                        $name = $valid($clean($cells[$j]));
                        if ($name === null) continue;
                        $out[$name] = max($out[$name] ?? 0, (float) $pm[1]);
                        break;
                    }
                    break;
                }
                continue;
            }
            if (preg_match_all('/([가-힣][가-힣A-Za-z·\s]{1,28}?)\s*\(\s*(\d{1,2})\s*점\s*\)/u', str_replace('*', '', $t), $mm, PREG_SET_ORDER)) {
                foreach ($mm as $x) {
                    $name = $valid($clean($x[1]));
                    if ($name === null) continue;
                    $out[$name] = max($out[$name] ?? 0, (float) $x[2]);
                }
            }
        }
        $out = array_filter($out, static fn($p) => $p >= 2 && $p <= 40);
        arsort($out);
        return $out;
    }

    /** 배점이 큰 항목(10점 이상, 없으면 상위 3개) */
    private static function bigItems(string $src): array
    {
        $all = self::evalItems($src);
        if (count($all) < 3) return [];
        $big = array_filter($all, static fn($p) => $p >= 10);
        return $big ?: array_slice($all, 0, 3, true);
    }

    private static function lengthFor(string $mood): array
    {
        return match ($mood) {
            '문제 제기', '배경·현황' => [220, 350],
            '해결·제안', '절차·방법' => [350, 550],
