    /**
     * 대본 판정. in: {script:{slides:[…]} 또는 slides 를 바로, plan?:{slides:[{n,title,keyword,message}]}, minutes?:전체 발표 분}
     */
    public static function checkScript(array $in): array
    {
        $doc = is_array($in['script'] ?? null) ? $in['script'] : $in;
        $slides = is_array($doc['slides'] ?? null) ? array_values(array_filter($doc['slides'], 'is_array')) : [];
        $planSlides = array_values(array_filter((array) (($in['plan']['slides'] ?? null) ?: []), 'is_array'));
        $issues = [];
        $add = static function (?int $n, string $sev, string $issue, string $fix) use (&$issues): void {
            $issues[] = ['where' => $n === null ? '전체' : $n . '쪽', 'severity' => $sev, 'issue' => $issue, 'fix' => $fix];
        };
        if (!$slides) {
            $add(null, 'fatal', 'slides 배열이 없습니다', '{"slides":[{"n":1,"keep":"…","lines":["…"]}]} 형식으로 보내세요');
            return self::score($issues, ['slides' => 0]);
        }
        $ns = array_map(static fn($s) => (int) ($s['n'] ?? 0), $slides);
        if ($planSlides) {
            $pn = array_map(static fn($s) => (int) ($s['n'] ?? 0), $planSlides);
            $miss = array_values(array_diff($pn, $ns));
            $extra = array_values(array_diff($ns, $pn));
            if ($miss) $add(null, 'fatal', '대본이 빠진 장: ' . implode(', ', $miss) . '쪽', '기획의 모든 장에 대본을 쓰세요');
            if ($extra) $add(null, 'warn', '기획에 없는 장: ' . implode(', ', $extra) . '쪽', 'n 을 기획의 쪽 번호와 같게');
        }
        // 장마다 목표 초 — Script::make 와 같은 셈(전체 분이 있으면 여유를 빼고 기획 글 양으로 나눔, 없으면 장당 60초)
        // seconds_per_slide 를 주면 장당 그 초가 목표(30초 대본 등, 2026-10-12 MCP 시험)
        $count = max(count($slides), count($planSlides));
        $sps = isset($in['seconds_per_slide']) && (float) $in['seconds_per_slide'] > 0 ? max(10.0, min(300.0, (float) $in['seconds_per_slide'])) : 0.0;
        $hasMin = isset($in['minutes']) && (float) $in['minutes'] > 0;
        $timed = $sps > 0 || $hasMin;
        if ($sps > 0) { $goal = $count * $sps; $speak = $goal; }
        else {
            $goal = $hasMin ? min((float) $in['minutes'] * 60, $count * Script::MAX_SLIDE + 30) : $count * Script::PER_SLIDE;
            $speak = $goal - max(30, $goal * 0.08);
        }
        $source = (string) ($in['source'] ?? '');
        // 수치 대조 기준 = 기획 전체 + 원자료 — 다른 장이나 원자료에 있는 수치는 지어낸 게 아니다
        $refFlat = self::norm(implode('', array_map(static fn($p) => ($p['title'] ?? '') . ($p['message'] ?? '') . ($p['content'] ?? ''), $planSlides)) . $source);
        $len = [];
        foreach ($planSlides ?: $slides as $s) $len[(int) ($s['n'] ?? 0)] = mb_strlen((string) ($s['content'] ?? implode('', (array) ($s['lines'] ?? []))));
        $avg = max(1, array_sum($len) / max(1, count($len)));
        $w = array_map(static fn($l) => 0.7 + 0.4 * min(2, $l / $avg), $len);
        $target = [];
        foreach ($w as $n => $x) $target[$n] = $sps > 0 ? (int) round($sps) : max(20, (int) round($speak * $x / max(0.001, array_sum($w)) / 5) * 5);
        $planBy = [];
        foreach ($planSlides as $p) $planBy[(int) ($p['n'] ?? 0)] = $p;
        $totalSec = 0.0;
        $last = end($ns);
        $per = [];
        foreach ($slides as $i => $s) {
            $n = (int) ($s['n'] ?? 0);
            $lines = array_map(static fn($l) => trim((string) $l), (array) ($s['lines'] ?? []));
            $spoken = array_values(array_filter($lines, static fn($l) => $l !== ''));
            if (!$spoken) { $add($n, 'fatal', 'lines(읽을 말)가 비었습니다', '한 항목에 한 문장씩 적으세요'); continue; }
            $sec = Script::secOf($lines);
            $totalSec += $sec;
            $chars = array_sum(array_map(static fn($l) => mb_strlen((string) preg_replace('/\*/u', '', $l)), $spoken));
            $tg = $target[$n] ?? ($sps > 0 ? (int) round($sps) : Script::PER_SLIDE);
            $per[] = ['n' => $n, 'sec' => round($sec), 'target_sec' => $tg, 'chars' => $chars, 'target_chars' => (int) round($tg * self::CHARS_PER_SEC)];
            if ($sec > $tg * 2.5 + 10) $add($n, 'fatal', '읽는 데 약 ' . (int) round($sec) . '초 — 목표 ' . $tg . '초의 두 배를 훨씬 넘습니다', '이 장은 남길 문장과 근거 한두 개만 두고 나머지를 지우세요');
            elseif ($sec > $tg * 1.15 + 5) $add($n, 'warn', '읽는 데 약 ' . (int) round($sec) . '초 — 목표 ' . $tg . '초를 넘습니다', '근거 문장을 줄이세요(남길 문장은 유지)');
            elseif ($sec < $tg * 0.5) $add($n, 'info', '약 ' . (int) round($sec) . '초로 목표 ' . $tg . '초의 절반이 안 됩니다', '근거 하나를 더하거나 그대로 두세요(짧은 건 괜찮습니다)');
            $keep = trim((string) ($s['keep'] ?? ''));
            if ($keep === '') $add($n, 'warn', 'keep(남길 문장)이 없습니다', '이 장에서 꼭 남길 한 문장을 적으세요');
            else {
                $kl = mb_strlen($keep);
                if ($kl < 15 || $kl > 60) $add($n, 'info', 'keep 이 ' . $kl . '자입니다(25~50자)', '한 문장으로 다듬으세요');
                $flat = self::norm(str_replace('*', '', implode('', $spoken)));
                if (!str_contains($flat, self::norm(str_replace('*', '', $keep)))) $add($n, 'warn', 'keep 문장이 lines 안에 그대로 없습니다', 'lines 에 그 문장을 그대로 넣으세요');
            }
            foreach ($spoken as $l) {
                $ll = mb_strlen((string) preg_replace('/\*/u', '', $l));
                if ($ll > 70) { $add($n, 'warn', '긴 문장(' . $ll . '자): "' . mb_substr($l, 0, 30) . '…"', '두 문장으로 나누세요(25~60자)'); break; }
            }
            foreach ($spoken as $l) {
                if (preg_match('/[.?!]\s+\S.*[.?!]$/u', $l)) { $add($n, 'info', '한 줄에 문장이 둘 이상입니다: "' . mb_substr($l, 0, 30) . '…"', '한 줄에 한 문장'); break; }
            }
            $txt = implode("\n", $spoken);
            foreach (self::BANNED_SCRIPT as $bw) if (str_contains($txt, $bw)) $add($n, 'warn', '쓰지 않는 말 "' . $bw . '"', '근거·방법으로 바꾸세요');
            // 숫자·산출물 없는 약속("최선을 다하겠습니다")은 대본에서도 경고 — 기획에만 있던 검사(2026-10-10 MCP 시험)
            foreach ($spoken as $l) {
                if (preg_match(self::VAGUE, $l) && !preg_match('/\d/', $l)) { $add($n, 'warn', '추상적인 약속: "' . mb_substr(trim(str_replace('*', '', $l)), 0, 40) . '"', '산출물·기한·수치로 바꾸세요(예: 착수 2주 내 ○○ 보고서)'); break; }
            }
            $em = preg_match_all('/\*\*[^*]+\*\*/u', $txt);
            if ($em === 0) $add($n, 'info', '강조(**…**)가 없습니다', '핵심 수치·결론 2~4곳을 감싸세요');
            elseif ($em > 5) $add($n, 'info', '강조가 ' . $em . '곳으로 많습니다', '2~4곳으로 줄이세요');
            $nonFormal = 0;
            foreach ($spoken as $l) if (!preg_match('/(니다|니까|세요|습니까|십시오|요)[.?!]?["”’)]?$/u', $l)) $nonFormal++;
            if ($nonFormal > max(1, (int) floor(count($spoken) / 3))) $add($n, 'info', '합니다체가 아닌 줄이 ' . $nonFormal . '개입니다', '"~합니다" 구어로 맞추세요');
            if ($i === 0 && preg_match('/^(안녕하|반갑습니다|소개드|발표를 맡)/u', $spoken[0])) $add($n, 'warn', '첫 장이 인사로 시작합니다', '인사 없이 바로 문제로 시작하세요');
            if ($n === $last && !str_contains(end($spoken), '감사합니다')) $add($n, 'warn', '마지막 장이 "감사합니다."로 끝나지 않습니다', '요청·약속 한두 문장 뒤 "감사합니다."');
            // 기획 핵심어가 대본에 있는가
            $p = $planBy[$n] ?? null;
            if ($p) {
                $kws = array_filter(array_map('trim', explode(',', (string) ($p['keyword'] ?? ''))));
                $flatTxt = self::norm(str_replace('*', '', $txt));
                foreach ($kws as $kw) if (!str_contains($flatTxt, self::norm($kw))) $add($n, 'warn', '기획 핵심어 "' . $kw . '" 가 대본에 없습니다', '결론 문장에 그 말을 넣으세요');
                $planFlat = self::norm(($p['title'] ?? '') . ($p['message'] ?? '') . ($p['content'] ?? ''));
                $seen = [];
                foreach (self::nums($txt) as $sn) {
                    if ($sn['unit'] === '' || isset($seen[$sn['key']]) || str_contains($planFlat, $sn['key'])) continue;
                    $seen[$sn['key']] = true;
                    // 기획 다른 장·원자료에 있으면 지어낸 수치가 아니다 — 그 장 기획에 넣으라는 경고만(2026-10-12 MCP 시험: 원자료 '2.3회' 치명)
                    if (str_contains($refFlat, $sn['key'])) $add($n, 'warn', '수치 "' . $sn['raw'] . '" 가 이 장 기획에는 없습니다(원자료·다른 장에는 있음)', '이 장 기획 content 에도 그 수치를 적거나, 그 수치가 있는 장에서 말하세요');
                    else $add($n, 'fatal', '수치 "' . $sn['raw'] . '" 가 기획·원자료 어디에도 없습니다', '기획(자료)에 있는 수치만 말하세요');
                }
            } elseif (!$planSlides && $source !== '') {
                $seen = [];
                foreach (self::nums($txt) as $sn) {
                    if ($sn['unit'] === '' || isset($seen[$sn['key']]) || str_contains($refFlat, $sn['key'])) continue;
                    $seen[$sn['key']] = true;
                    $add($n, 'fatal', '수치 "' . $sn['raw'] . '" 가 원자료에 없습니다', '원자료에 있는 수치만 말하세요');
                }
            }
        }
        // 발표자 = PM 본인 — 1인칭, 블라인드면 "저희 제안사", 큰 배점 항목은 예상 질문(Script.php 규칙을 판정에도, DCK-109)
        $all = str_replace('*', '', implode("\n", array_merge(...array_map(static fn($s) => array_map('strval', (array) ($s['lines'] ?? [])), $slides))));
        $nLines = count(array_filter(preg_split('/\n/u', $all), static fn($l) => trim($l) !== ''));
        $first = preg_match_all('/(저는|제가|저희|PM\s*으로서|PM\s*으로)/u', $all);
        if ($nLines >= 6 && $first === 0) $add(null, 'warn', '발표자 1인칭(저는·제가·저희)이 한 번도 없습니다', '발표자는 PM 본인입니다 — "저는 이 사업의 PM으로서 …" 처럼 책임을 1인칭으로 말하세요');
        elseif ($nLines >= 20 && $first < 2) $add(null, 'info', '1인칭이 ' . $first . '번뿐입니다', '첫 장·약속·마무리에서 PM 1인칭으로 말하세요');
        $planTxt = implode("\n", array_map(static fn($p) => ($p['title'] ?? '') . "\n" . ($p['message'] ?? '') . "\n" . ($p['content'] ?? ''), $planSlides));
        $blind = !empty($in['blind']) || preg_match('/블라인드|blind/iu', $source . "\n" . $planTxt);
        if ($blind && !str_contains($all, '저희 제안사')) $add(null, 'warn', '블라인드 평가인데 "저희 제안사"가 없습니다', '회사명·제품명 대신 "저희 제안사"로 부르세요');
        $qa = (array) ($doc['qa'] ?? $in['qa'] ?? []);
        $loose = static fn(string $t): string => (string) preg_replace('/(?:및|·|ㆍ|,|&)/u', '', self::norm($t));
        $qaTxt = $loose((string) json_encode($qa, JSON_UNESCAPED_UNICODE));
        $big = self::bigItems($source);
        if ($big && !$qa) $add(null, 'warn', '예상 질문(qa)이 없습니다 — 배점이 큰 항목: ' . implode(', ', array_slice(array_keys($big), 0, 3)), '배점 상위 항목마다 평가위원 질문과 30초 답변을 준비하세요(qa:[{q,a,slide}])');
        elseif ($big) {
            $miss = [];
            // 항목 이름 통째가 아니라 핵심 낱말로 본다 — "보안·개인정보 보호는?" 이 "…보호 방안" 질문으로 인정되게(2026-10-12 예시 검증)
            $core = static function (string $name) use ($loose): array {
                $w = preg_split('/[\s·ㆍ,&\/()]+|및/u', $name) ?: [];
                $w = array_map(static fn($x) => (string) preg_replace('/(방안|계획|전략|체계|방향|이해도|기술|관리|수립)$/u', '', $x), $w);
                return array_values(array_filter(array_map($loose, $w), static fn($x) => mb_strlen($x) >= 2));
            };
            foreach (array_slice(array_keys($big), 0, 3) as $name) {
                $ws = $core($name);
                $hit = $ws ? count(array_filter($ws, static fn($x) => str_contains($qaTxt, $x))) >= max(1, (int) ceil(count($ws) / 2)) : str_contains($qaTxt, $loose($name));
                if (!$hit) $miss[] = $name;
            }
            if ($miss) $add(null, 'info', '배점 큰 항목의 예상 질문이 없습니다: ' . implode(', ', $miss), '그 항목 이름으로 질문 하나씩');
        } elseif (!$qa && count($slides) >= 8) $add(null, 'info', '예상 질문(qa)이 없습니다', '평가위원이 물을 질문 3~5개와 답을 준비하세요');
        $stat = ['slides' => count($slides), 'total_sec' => (int) round($totalSec), 'goal_sec' => (int) round($goal), 'per_slide' => $per, 'first_person' => $first, 'blind' => (bool) $blind, 'qa' => count($qa)];
        if ($sps > 0) $stat['seconds_per_slide'] = (int) round($sps);
        $mmss = static fn(float $t): string => (int) floor($t / 60) . '분 ' . ((int) round($t) % 60) . '초';
        // 너무 짧은 대본도 통과시키지 않는다 — 15분 발표에 7분 대본이 통과하던 것(2026-10-12 MCP 시험)
        if ($timed && $totalSec < $goal * 0.6) $add(null, 'fatal', '전체 약 ' . $mmss($totalSec) . '로 목표 ' . $mmss($goal) . '의 60%에 못 미칩니다', '발표 시간이 남습니다 — 짧은 장부터 근거 문장(수치·사례)을 더하세요. 장마다 목표는 stat.per_slide.target_sec');
        elseif ($timed && $totalSec < $goal * 0.8) $add(null, 'warn', '전체 약 ' . $mmss($totalSec) . '로 목표 ' . $mmss($goal) . '보다 꽤 짧습니다', '짧은 장에 근거 하나씩 더하세요');
        if ($timed && $totalSec > $goal * 1.5) $add(null, 'fatal', '전체 약 ' . (int) round($totalSec / 60) . '분 ' . ((int) round($totalSec) % 60) . '초로 목표 ' . round($goal / 60, 1) . '분의 1.5배를 넘습니다', '발표 시간 안에 못 끝냅니다 — 긴 장부터 근거 문장을 줄이세요');
        elseif ($timed && $totalSec > $goal) $add(null, 'warn', '전체 약 ' . (int) round($totalSec / 60) . '분 ' . ((int) round($totalSec) % 60) . '초로 목표 ' . round($goal / 60, 1) . '분을 넘습니다', '긴 장부터 근거 문장을 줄이세요');
        return self::score($issues, $stat);
    }

    // ───────────────────────── 공통 ─────────────────────────

    /** 점수 — fatal 15, warn 5, info 1 감점. 통과 = 85점 이상이고 fatal 0 */
    private static function score(array $issues, array $stat): array
    {
        $w = ['fatal' => 15, 'warn' => 5, 'info' => 1];
        $pen = 0;
        $cnt = ['fatal' => 0, 'warn' => 0, 'info' => 0];
        foreach ($issues as $x) { $pen += $w[$x['severity']] ?? 1; $cnt[$x['severity']] = ($cnt[$x['severity']] ?? 0) + 1; }
        $score = max(0, 100 - $pen);
        // 판정할 장이 하나도 없으면 0점 — 빈 기획이 85점으로 보이던 것(2026-10-10 MCP 시험)
        if (($stat['slides'] ?? null) === 0) $score = 0;
        // 치명이 있으면 통과선(85) 아래로 — 점수만 보고 통과로 오해하지 않게
        if ($cnt['fatal'] > 0) $score = min($score, 84);
        $sev = ['fatal' => 0, 'warn' => 1, 'info' => 2];
        usort($issues, static fn($a, $b) => ($sev[$a['severity']] ?? 3) <=> ($sev[$b['severity']] ?? 3));
        return ['score' => $score, 'pass' => $score >= 85 && $cnt['fatal'] === 0, 'counts' => $cnt, 'fixes' => array_slice($issues, 0, 60), 'stat' => $stat];
    }
